import 'package:spectrum/spectrum.dart';

/// Spectrum Accordion Item: an item of a SpectrumAccordion. As in Spectrum 2,
/// it is a SpectrumDisclosure, whose expansion is decided by the accordion.
typedef SpectrumAccordionItem = SpectrumDisclosure;

/// Header of a SpectrumAccordionItem, the same as a SpectrumDisclosureHeader.
typedef SpectrumAccordionItemHeader = SpectrumDisclosureHeader;

/// Title of a SpectrumAccordionItem, the same as a SpectrumDisclosureTitle.
typedef SpectrumAccordionItemTitle = SpectrumDisclosureTitle;

/// Panel of a SpectrumAccordionItem, the same as a SpectrumDisclosurePanel.
typedef SpectrumAccordionItemPanel = SpectrumDisclosurePanel;
